module alu_riscv(
    input [31:0] A,
    input [31:0] B,
    input [6:0] op,
    input [2:0] funct3,
    input [6:0] funct7,

    output reg [31:0] result,
    output reg zero,
    output reg carry,
    output reg overflow
);

    //--------------------------------------------------
    // ALU Operations
    //--------------------------------------------------
    // 0000000 - ADD
    // 0000001 - AND
    // 0000010 - OR
    // 0000011 - SUB
    // 0000100 - XOR
    // 0000101 - SLT
    // 0000110 - NOR
    // 0000111 - SHIFT
    // 0001000 - MUL
    // 0100000 - BEQ
    // 0100001 - BNE
    // 0100010 - BLT
    // 0100011 - BGE
    //--------------------------------------------------

    wire signed [31:0] A_signed = A;
    wire signed [31:0] B_signed = B;

    //--------------------------------------------------
    // Multiplier
    //--------------------------------------------------
    wire [63:0] mul_product;

    shift_add_mul u_mul(
        .A(A),
        .B(B),
        .product(mul_product)
    );

    //--------------------------------------------------
    // ALU Logic
    //--------------------------------------------------
    always @(*) begin

        // defaults
        result   = 32'd0;
        carry    = 1'b0;
        overflow = 1'b0;

        case(op)

            //--------------------------------------------------
            // ADD
            //--------------------------------------------------
            7'b0000000: begin
                {carry, result} = A + B;
                overflow = ((A[31] == B[31]) &&
                            (result[31] != A[31]));
            end

            //--------------------------------------------------
            // AND
            //--------------------------------------------------
            7'b0000001: begin
                result = A & B;
            end

            //--------------------------------------------------
            // OR
            //--------------------------------------------------
            7'b0000010: begin
                result = A | B;
            end

            //--------------------------------------------------
            // SUB
            //--------------------------------------------------
            7'b0000011: begin
                result = A - B;
                carry = (A < B);

                overflow =
                    ((A[31] != B[31]) &&
                     (result[31] != A[31]));
            end

            //--------------------------------------------------
            // XOR
            //--------------------------------------------------
            7'b0000100: begin
                result = A ^ B;
            end

            //--------------------------------------------------
            // SLT
            //--------------------------------------------------
            7'b0000101: begin
                result = (A_signed < B_signed) ?
                          32'd1 : 32'd0;
            end

            //--------------------------------------------------
            // NOR
            //--------------------------------------------------
            7'b0000110: begin
                result = ~(A | B);
            end

            //--------------------------------------------------
            // SHIFT OPERATIONS
            //--------------------------------------------------
            7'b0000111: begin

                case(funct3)

                    // SLL / SLLI
                    3'b001: begin
                        result = A << B[4:0];
                    end

                    // SRL / SRA
                    3'b101: begin

                        if(funct7 == 7'b0000000)
                            result = A >> B[4:0];

                        else if(funct7 == 7'b0100000)
                            result = $signed(A) >>> B[4:0];
                    end

                    default: begin
                        result = 32'd0;
                    end

                endcase
            end

            //--------------------------------------------------
            // MUL (RV32M)
            //--------------------------------------------------
            7'b0001000: begin
                result = mul_product[31:0];
            end

            //--------------------------------------------------
            // BEQ
            //--------------------------------------------------
            7'b0100000: begin
                result = (A == B) ? 32'd1 : 32'd0;
            end

            //--------------------------------------------------
            // BNE
            //--------------------------------------------------
            7'b0100001: begin
                result = (A != B) ? 32'd1 : 32'd0;
            end

            //--------------------------------------------------
            // BLT
            //--------------------------------------------------
            7'b0100010: begin
                result = (A_signed < B_signed) ?
                         32'd1 : 32'd0;
            end

            //--------------------------------------------------
            // BGE
            //--------------------------------------------------
            7'b0100011: begin
                result = (A_signed >= B_signed) ?
                         32'd1 : 32'd0;
            end

            //--------------------------------------------------
            // DEFAULT
            //--------------------------------------------------
            default: begin
                result   = 32'd0;
                carry    = 1'b0;
                overflow = 1'b0;
            end

        endcase

        zero = (result == 32'd0);

    end

endmodule
